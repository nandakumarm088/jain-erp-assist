// Focused checks for the Porcelain Blue layout and optional Theory/Lab override.
const {chromium}=require('@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const root=path.resolve(__dirname,'..');
const url='https://jained.jgianveshana.com/UI/Academics/Class%20Attendance/JVPL_Regular_Class_Attendance.aspx';
const complete={dateMode:'current',classType:'lab',date:'05/11/2026',fields:{attendanceType:['at-lab'],program:['p1'],batch:['b1'],semester:['sem5'],specialization:['cyber'],course:['lab502'],section:['section-lab1'],session:['period1']}};
let context;
(async()=>{
  const fixture=await fs.readFile(path.join(__dirname,'fixture.html'),'utf8');
  const profile=await fs.mkdtemp(path.join(os.tmpdir(),'classflow-type-'));
  const cached=path.join(process.env.LOCALAPPDATA||'','ms-playwright','chromium-1243','chrome-win64','chrome.exe');
  const executablePath=process.env.CLASSFLOW_TEST_CHROMIUM||(await fs.access(cached).then(()=>cached).catch(()=>undefined));
  context=await chromium.launchPersistentContext(profile,{headless:true,channel:executablePath?undefined:'chromium',executablePath,args:[`--disable-extensions-except=${root}`,`--load-extension=${root}`]});
  await context.route('https://jained.jgianveshana.com/**',route=>route.fulfill({contentType:'text/html',body:fixture}));
  const worker=context.serviceWorkers()[0]||await context.waitForEvent('serviceworker');
  const site=await context.newPage();await site.goto(url);
  const tabId=await worker.evaluate(async()=>(await chrome.tabs.query({})).find(tab=>tab.url?.includes('JVPL_Regular_Class_Attendance'))?.id);
  const seed=async data=>{await site.evaluate(data=>{sessionStorage.setItem('fixture',JSON.stringify(data));sessionStorage.removeItem('history');},data);await site.reload();};
  await seed(complete);
  const panel=await context.newPage();
  await panel.addInitScript(tabId=>{const send=chrome.runtime.sendMessage.bind(chrome.runtime);chrome.runtime.sendMessage=message=>send({...message,tabId});},tabId);
  await panel.goto(`chrome-extension://${new URL(worker.url()).host}/sidepanel.html`);await panel.setViewportSize({width:360,height:900});
  await panel.getByRole('button',{name:'Save this class',exact:true}).click();await panel.locator('#cf-form').waitFor();
  assert.equal(await panel.locator('#cf-run-attendance').count(),0);
  const captured=await panel.evaluate(()=>chrome.runtime.sendMessage({type:'STATE'}));
  assert.equal(captured.snapshot.fields.attendanceType,undefined);
  assert.equal(captured.settings.attendanceType,undefined);
  assert.equal(JSON.stringify(await worker.evaluate(()=>chrome.storage.local.get(null))).includes('"attendanceType"'),false);
  const mode=()=>panel.getByRole('group',{name:'Preset class type',exact:true});
  assert.equal(await mode().getByRole('button',{name:'Filters only',exact:true}).getAttribute('aria-pressed'),'true');
  await panel.locator('#cf-name').fill('Cyber Security Lab');
  await mode().getByRole('button',{name:'Lab',exact:true}).click();
  assert.match(await panel.locator('#cf-save-summary').innerText(),/Saving as Lab.*overrides/s);
  await panel.locator('.cf-save-mode').scrollIntoViewIfNeeded();
  await fs.mkdir(path.join(root,'artifacts'),{recursive:true});await panel.screenshot({path:path.join(root,'artifacts','porcelain-save-options.png')});
  await panel.getByRole('button',{name:'Save preset',exact:true}).click();
  await panel.getByRole('button',{name:'Cyber Security Lab',exact:true}).waitFor();
  const saved=()=>worker.evaluate(async()=>(await chrome.storage.local.get('classflow.presets'))['classflow.presets'][0]);
  assert.equal((await saved()).classTypeOverride,'lab');
  const order=await panel.evaluate(()=>({settings:document.querySelector('.cf-runtime').getBoundingClientRect().bottom,classes:document.querySelector('.cf-library').getBoundingClientRect().top}));
  assert.ok(order.settings<=order.classes,'Attendance settings precede saved classes');
  await panel.screenshot({path:path.join(root,'artifacts','porcelain-panel.png')});
  const original=await saved();
  for(const name of ['Semester 5','Semester 3'])await panel.evaluate(name=>chrome.runtime.sendMessage({type:'CREATE_CATEGORY',name}),name);
  await panel.evaluate(preset=>chrome.runtime.sendMessage({type:'SAVE_PRESET',preset}),{...original,category:'Semester 5'});
  await panel.evaluate(preset=>chrome.runtime.sendMessage({type:'SAVE_PRESET',preset}),{...original,id:'second',name:'Second class',category:'Semester 5'});
  const group=name=>panel.locator(`[data-category-key="category:${name.toLowerCase()}"]`);
  await group('Semester 5').waitFor();await panel.getByRole('button',{name:'Second class',exact:true}).waitFor();
  assert.equal(await group('Semester 5').locator('.cf-preset').count(),2);
  const style=await group('Semester 5').locator('.cf-category-toggle').evaluate(el=>({background:getComputedStyle(el).backgroundColor,border:getComputedStyle(el).borderBottomWidth}));
  assert.equal(style.background,'rgba(0, 0, 0, 0)');assert.equal(style.border,'0px');
  await group('Semester 5').locator('.cf-category-toggle').click();
  await panel.waitForFunction(()=>document.querySelector('[data-category-key="category:semester 5"] .cf-category-toggle').getAttribute('aria-expanded')==='false');
  await panel.getByRole('button',{name:'Rename category Semester 5',exact:true}).click();
  await panel.getByRole('textbox',{name:'Rename category',exact:true}).fill('Fifth semester');
  await panel.getByRole('textbox',{name:'Rename category',exact:true}).press('Enter');
  await group('Fifth semester').waitFor();
  assert.equal(await group('Fifth semester').locator('.cf-category-toggle').getAttribute('aria-expanded'),'false');
  const stored=()=>worker.evaluate(async()=>chrome.storage.local.get(['classflow.presets','classflow.categories','classflow.collapsedCategories']));
  let state=await stored();assert.equal(state['classflow.presets'].filter(p=>p.category==='Fifth semester').length,2);
  assert.equal(state['classflow.collapsedCategories'].includes('category:semester 5'),false);
  assert.equal(state['classflow.collapsedCategories'].includes('category:fifth semester'),true);
  const archive=await panel.evaluate(()=>chrome.runtime.sendMessage({type:'EXPORT_PRESETS'}));
  assert.ok(archive.backup.categories.includes('Fifth semester'));assert.equal(archive.backup.presets.filter(p=>p.category==='Fifth semester').length,2);
  await panel.reload();await group('Fifth semester').waitFor();
  assert.equal(await group('Fifth semester').locator('.cf-category-toggle').getAttribute('aria-expanded'),'false');
  // A case-only rename is allowed and keeps a single category.
  await panel.getByRole('button',{name:'Rename category Semester 3',exact:true}).click();
  await panel.getByRole('textbox',{name:'Rename category',exact:true}).fill('semester 3');
  await panel.getByRole('button',{name:'Save',exact:true}).click();
  await panel.getByRole('button',{name:'Rename category semester 3',exact:true}).waitFor();
  assert.equal((await stored())['classflow.categories'].filter(name=>name.toLowerCase()==='semester 3').length,1);
  // Conflicting names cannot silently merge categories.
  await panel.getByRole('button',{name:'Rename category Fifth semester',exact:true}).click();
  await panel.getByRole('textbox',{name:'Rename category',exact:true}).fill('semester 3');
  await panel.getByRole('button',{name:'Save',exact:true}).click();
  await panel.getByRole('alert').filter({hasText:'already exists'}).waitFor();
  assert.equal((await stored())['classflow.presets'].filter(p=>p.category==='Fifth semester').length,2);
  await panel.getByRole('button',{name:'Cancel category rename',exact:true}).click();
  // Cancellation is reversible and confirmation clearly describes the result.
  await panel.getByRole('button',{name:'Delete category Fifth semester',exact:true}).click();
  const confirmation=panel.getByRole('group',{name:'Delete Fifth semester',exact:true});
  assert.match(await confirmation.innerText(),/Classes move to Uncategorized/);
  await confirmation.getByRole('button',{name:'Cancel',exact:true}).click();assert.equal(await confirmation.count(),0);
  await panel.getByRole('button',{name:'Delete category Fifth semester',exact:true}).click();
  await panel.getByRole('group',{name:'Delete Fifth semester',exact:true}).getByRole('button',{name:'Delete',exact:true}).click();
  await panel.locator('[data-category-key="uncategorized"]').getByRole('button',{name:'Cyber Security Lab',exact:true}).waitFor();
  state=await stored();assert.equal(state['classflow.presets'].length,2);assert.ok(state['classflow.presets'].every(p=>p.category===''));
  assert.equal(state['classflow.collapsedCategories'].includes('category:fifth semester'),false);
  assert.deepEqual(state['classflow.presets'].find(p=>p.id===original.id).fields,original.fields);
  assert.equal(state['classflow.categories'].includes('Fifth semester'),false);
  await panel.getByRole('button',{name:'Delete category semester 3',exact:true}).click();
  await panel.getByRole('group',{name:'Delete semester 3',exact:true}).getByRole('button',{name:'Delete',exact:true}).click();
  await panel.getByRole('button',{name:'Cyber Security Lab',exact:true}).waitFor();
  state=await stored();assert.equal(state['classflow.presets'].length,2);assert.deepEqual(state['classflow.categories'],[]);
  for(const width of [360,240,200]){
    await panel.setViewportSize({width,height:800});
    assert.equal(await panel.evaluate(()=>[...document.querySelectorAll('button,input,select')].every(el=>{const r=el.getBoundingClientRect();return !r.width||r.right<=innerWidth;})),true);
  }
  console.log('PASS: compact divider, rename and case changes, conflict handling, persisted collapse, category deletion confirmation, uncategorized classes, backups, and narrow layout');
  await context.close();context=null;
})().catch(async error=>{console.error(error);if(context)await context.close();process.exitCode=1;});
